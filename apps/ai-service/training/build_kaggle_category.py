"""Packages the Task 04.2-Q real-photo dataset and a GPU kernel that trains several candidates in one session.

    python build_kaggle_category.py --user <kaggle-user> --dataset-root .data/realphoto-v1/dataset \
        --out .data/kaggle-q --run "B:--unfreeze-stages 0 --model-version effb0-realphoto-b1" \
        --run "C:--unfreeze-stages 3 --model-version effb0-realphoto-c1"

The kernel embeds the repository's serving network and training modules verbatim and writes each run to
/kaggle/working/<name>/. The final benchmark folder is never packaged. No credentials, database URLs or customer data
are included; internet is enabled only so torchvision can fetch ImageNet weights.
"""

from __future__ import annotations

import argparse
import json
import shlex
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODULES = [
    HERE.parent / "app" / "models" / "embedding_network.py",
    *(HERE / "src" / name for name in ("data.py", "export.py", "train_category.py")),
]
DATASET_SLUG = "electrohub-realphoto-v1"
KERNEL_SLUG = "electrohub-realphoto-train"
FORBIDDEN_NAMES = (".env", "kaggle.json", "password", "credential", "secret")


def kernel_source(runs: list[tuple[str, list[str]]]) -> str:
    modules = {path.name: path.read_text(encoding="utf-8") for path in MODULES}
    return f'''"""ElectroHub Task 04.2-Q category-aware training (generated by build_kaggle_category.py)."""
import json, subprocess, sys
from pathlib import Path

SRC = Path("/kaggle/working/src")
SRC.mkdir(parents=True, exist_ok=True)
for name, text in {json.dumps(modules)}.items():
    (SRC / name).write_text(text, encoding="utf-8")
print(subprocess.run(["nvidia-smi"], capture_output=True, text=True).stdout, flush=True)
data = next(Path("/kaggle/input").glob("**/manifests/images.csv")).parent.parent
status = {{}}
for name, extra in {json.dumps(runs)}:
    args = ["--data", str(data), "--out", f"/kaggle/working/{{name}}", "--workers", "4", *extra]
    status[name] = subprocess.call([sys.executable, str(SRC / "train_category.py"), *args], cwd=SRC)
    print(json.dumps({{"run": name, "exit": status[name]}}), flush=True)
sys.exit(1 if any(status.values()) else 0)
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--user", required=True)
    parser.add_argument("--dataset-root", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--run", action="append", required=True, help="NAME:train_category.py arguments")
    parser.add_argument("--dataset-slug", default=DATASET_SLUG)
    parser.add_argument("--kernel-slug", default=KERNEL_SLUG)
    args = parser.parse_args()

    report = json.loads((args.dataset_root / "dataset_report.json").read_text(encoding="utf-8"))
    if report["crossSplitSourceGroups"] != 0:
        raise SystemExit("refusing to package: a source group crosses train and evaluation splits")
    dataset = args.out / "dataset"
    if dataset.exists():
        shutil.rmtree(dataset)
    dataset.mkdir(parents=True)
    for name in ("manifests", "images", "license_attributions.md", "dataset_report.json"):
        source = args.dataset_root / name
        (shutil.copytree if source.is_dir() else shutil.copy2)(source, dataset / name)
    leaked = [p for p in dataset.rglob("*") if any(token in p.name.lower() for token in FORBIDDEN_NAMES)]
    if leaked or (dataset / "final_benchmark").exists():
        raise SystemExit(f"refusing to package: {leaked or 'final benchmark present'}")
    (dataset / "dataset-metadata.json").write_text(
        json.dumps(
            {
                "title": f"ElectroHub Real Photo Vision {args.dataset_slug.rsplit('-', 1)[-1]}",
                "id": f"{args.user}/{args.dataset_slug}",
                "licenses": [{"name": "other"}],
                "description": "Private training set: Wikimedia Commons and Openverse (Flickr) photographs under "
                "CC0/PD/CC BY/CC BY-SA, plus ElectroHub catalog illustrations. Per-file attribution in "
                "license_attributions.md.",
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    runs = [(spec.split(":", 1)[0], shlex.split(spec.split(":", 1)[1])) for spec in args.run]
    kernel = args.out / "kernel"
    kernel.mkdir(parents=True, exist_ok=True)
    (kernel / "electrohub_realphoto_train.py").write_text(kernel_source(runs), encoding="utf-8")
    (kernel / "kernel-metadata.json").write_text(
        json.dumps(
            {
                "id": f"{args.user}/{args.kernel_slug}",
                "title": args.kernel_slug.replace("-", " ").title(),
                "code_file": "electrohub_realphoto_train.py",
                "language": "python",
                "kernel_type": "script",
                "is_private": True,
                "enable_gpu": True,
                "enable_internet": True,
                "dataset_sources": [f"{args.user}/{args.dataset_slug}"],
                "competition_sources": [],
                "kernel_sources": [],
                "model_sources": [],
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    print(json.dumps({"dataset": str(dataset), "kernel": str(kernel), "runs": [name for name, _ in runs]}))


if __name__ == "__main__":
    main()

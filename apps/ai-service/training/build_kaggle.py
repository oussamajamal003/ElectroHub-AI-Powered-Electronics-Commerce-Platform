"""Prepares the PRIVATE Kaggle dataset folder and the GPU training kernel from repository sources.

    python build_kaggle.py --user <kaggle-username> --dataset-root .data/electrohub-commons-vision-v1 --out .data/kaggle

Produces:
  <out>/dataset/  dataset-metadata.json + a copy of the audited dataset (manifests, images, attributions, SHA256SUMS)
  <out>/kernel/   kernel-metadata.json + electrohub_vision_train.py (single self-contained script)

The kernel embeds the exact training modules and the serving network definition, so the notebook run is the same code
that the repository tests. Kaggle internet is enabled only so torchvision can fetch the ImageNet EfficientNet-B0
weights; no credentials, database URLs or customer data are packaged.
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODULES = [
    HERE.parent / "app" / "models" / "embedding_network.py",
    *(HERE / "src" / name for name in ("metrics.py", "losses.py", "data.py", "export.py", "train.py")),
]
DATASET_SLUG = "electrohub-commons-vision-v1"
KERNEL_SLUG = "electrohub-vision-train"
COPIED = ("manifests", "images", "license_attributions.md", "SHA256SUMS", "dataset_report.json")
FORBIDDEN_NAMES = (".env", "kaggle.json", "password", "credential", "secret")


def kernel_source(user: str, train_args: list[str]) -> str:
    modules = {path.name: path.read_text(encoding="utf-8") for path in MODULES}
    return f'''"""ElectroHub Task 04.2 - EfficientNet-B0 visual-embedding training (generated by build_kaggle.py)."""
import json, subprocess, sys
from pathlib import Path

SRC = Path("/kaggle/working/src")
SRC.mkdir(parents=True, exist_ok=True)
MODULES = {json.dumps(modules)}
for name, text in MODULES.items():
    (SRC / name).write_text(text, encoding="utf-8")
print(subprocess.run(["nvidia-smi"], capture_output=True, text=True).stdout)
data = next(Path("/kaggle/input").glob("**/manifests")).parent
args = ["--data", str(data), "--out", "/kaggle/working/run", *{json.dumps(train_args)}]
sys.exit(subprocess.call([sys.executable, str(SRC / "train.py"), *args], cwd=SRC))
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--user", required=True)
    parser.add_argument("--dataset-root", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--train-arg", action="append", default=[], help="extra train.py argument (repeatable)")
    args = parser.parse_args()

    report = json.loads((args.dataset_root / "dataset_report.json").read_text(encoding="utf-8"))
    audit = json.loads((args.dataset_root / "manifests" / "split_audit.json").read_text(encoding="utf-8"))
    if not (report["auditPassed"] and audit["passed"]):
        raise SystemExit("refusing to package: split audit has not passed")

    dataset = args.out / "dataset"
    if dataset.exists():
        shutil.rmtree(dataset)
    dataset.mkdir(parents=True)
    for name in COPIED:
        source = args.dataset_root / name
        if source.is_dir():
            shutil.copytree(
                source, dataset / name, ignore=shutil.ignore_patterns("commons_sources.json", "review.json")
            )
        else:
            shutil.copy2(source, dataset / name)
    leaked = [p for p in dataset.rglob("*") if any(token in p.name.lower() for token in FORBIDDEN_NAMES)]
    if leaked:
        raise SystemExit(f"refusing to package suspicious files: {leaked}")
    (dataset / "dataset-metadata.json").write_text(
        json.dumps(
            {
                "title": "ElectroHub Commons Vision v1",
                "id": f"{args.user}/{DATASET_SLUG}",
                "licenses": [{"name": "other"}],
                "description": "Private training set: Wikimedia Commons photographs (CC0/PD/CC BY/CC BY-SA). "
                "Per-file licence "
                "and attribution in license_attributions.md and manifests/image_provenance.csv.",
            },
            indent=2,
        ),
        encoding="utf-8",
    )

    kernel = args.out / "kernel"
    kernel.mkdir(parents=True, exist_ok=True)
    (kernel / "electrohub_vision_train.py").write_text(kernel_source(args.user, args.train_arg), encoding="utf-8")
    (kernel / "kernel-metadata.json").write_text(
        json.dumps(
            {
                "id": f"{args.user}/{KERNEL_SLUG}",
                "title": "ElectroHub Vision Train",
                "code_file": "electrohub_vision_train.py",
                "language": "python",
                "kernel_type": "script",
                "is_private": True,
                "enable_gpu": True,
                "enable_internet": True,
                "dataset_sources": [f"{args.user}/{DATASET_SLUG}"],
                "competition_sources": [],
                "kernel_sources": [],
                "model_sources": [],
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    print(
        json.dumps(
            {
                "dataset": str(dataset),
                "kernel": str(kernel),
                "images": sum(1 for _ in (dataset / "images").rglob("*.jpg")),
            }
        )
    )


if __name__ == "__main__":
    main()
